def puzzle(title, story, ans=None, hint=None):
    """Творча задача: умова, простір для міркувань і відповідь догори дриґом."""
    blocks = [text(f'<div class="puzzle">{story}</div>')]
    if hint:
        blocks.append(note(hint))
    blocks += [box('Мої ідеї та міркування (запишіть щонайменше три варіанти, перш ніж дивитися відповідь)', None, 'dots'),
               lines(3, 'Моя остаточна відповідь:')]
    ex = dict(title=title, goal='Потренувати нестандартне мислення: шукати рішення там, де «очевидного» немає.',
              blocks=blocks)
    if ans:
        ex['tail'] = [answer(ans)]
    return ex


