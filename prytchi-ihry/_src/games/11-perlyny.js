/* Гра 11 «98 перлин» — детектив за притчею «Намисто». */
(function () {
  const ROOMS = [
    { n: "Покої Панни", x: 0, y: 50, w: 320, h: 230, c: "#e8c9d6" },
    { n: "Сад", x: 640, y: 50, w: 320, h: 230, c: "#b9dba0" },
    { n: "Кухня", x: 0, y: 300, w: 320, h: 240, c: "#efdcb8" },
    { n: "Майстерня ювеліра", x: 640, y: 300, w: 320, h: 240, c: "#c9d3e6" },
    { n: "Хол", x: 320, y: 50, w: 320, h: 490, c: "#e6dfd2" },
  ];
  const PEOPLE = {
    panna: { e: "👸", x: 160, y: 175, n: "Панна" },
    sister: { e: "👩", x: 780, y: 165, n: "Сестра Оля" },
    friend: { e: "👱‍♀️", x: 150, y: 420, n: "Подруга Марта" },
    maid: { e: "👩‍🦳", x: 480, y: 250, n: "Служниця" },
    jeweler: { e: "👴", x: 810, y: 415, n: "Ювелір" },
  };
  const CLUES = [
    { k: "thread", e: "🧵", x: 890, y: 235, t: "Розірвана нитка в саду. Чиясь намистина розсипалася?" },
    { k: "pearls", e: "🦪", x: 260, y: 485, t: "Дві перлини на кухонному столі!" },
    { k: "note", e: "🧾", x: 60, y: 110, t: "Чек ювеліра: «…намисто, ⬛⬛ перлин». Цифру залила пляма чорнила." },
  ];
  const PETAL_T = 22;
  let S;

  const game = {
    id: "11", title: "98 перлин", parable: "Намисто",
    story: "Панні подарували намисто з перлин. Якось вона їх перерахувала: 98. «Хтось поцупив дві! Сестри? Подруги? Зрадниці!» Довго журилася вона, зів’яла її краса, і так і не дізналася, що в намисті завжди було 98 перлин.",
    goal: "Ти — детектив. Панна певна, що в неї вкрали дві перлини. Оглядай кімнати, допитуй людей, знайди правду, поки квітка у волоссі Панни не зів’яла.",
    controls: ["Стрілки або WASD — ходити", "Пробіл або E — оглянути доказ або допитати людину", "Щоб висунути звинувачення, поговори з Панною"],
    help: "<kbd>←↑→↓</kbd> ходити · <kbd>Пробіл</kbd> оглянути або допитати",
    actLabel: "Допит",
    endings: {
      "А": { title: "Звинуватив невинну", text: "Справедливість, здавалося б, тріумфувала, і стрічка дружби розірвалася. А наступного дня Ювелір сказав: «Їх завжди було 98»." },
      "Б": { title: "Правда", text: "Ти приніс Панні слова Ювеліра: перлин завжди було 98. Вона довго мовчала, а потім уперше за тиждень усміхнулася. Квітка у волоссі ожила." },
      "В": { title: "Квітка зів’яла", text: "Поки тривало розслідування, Панна зачинилася в покоях і озлобилася на всіх. Остання пелюстка впала, а правди так ніхто і не сказав." },
      "Г": { title: "Злочину не було", text: "Доказів правди ти не мав, але й винних не знайшов. «Може, нічого й не пропало?» — сказав ти. І Панна вирішила тішитися тим, що має." },
    },
    moral: "Нам часто здається, що хтось чогось недодав: часу, щастя, перлин. Не варто обманювати себе: щастя від самого початку повна чаша, і лише треба навчитися ним насолоджуватися.",
    questions: ["Яких «двох перлин» вам бракує? А чи були вони взагалі?", "Кого ви звинувачували у своїх «пропажах»?", "Скільки пелюсток уже впало, поки ви шукали винного?"],

    _s() { return S; },
    init(api) {
      S = { p: api.actor({ x: 480, y: 470, emoji: "🕵️", size: 40, speed: 175 }), found: new Set(), truth: false, petals: 6, petalT: PETAL_T, talked: {}, done: false, msg: "", msgT: 0, accusations: 0 };
    },
    async start(api) {
      await api.say([["Панна", "Детективе! У моєму намисті було сто перлин, а тепер 98! Хтось поцупив дві. Сестра? Подруга? Зрадниці!"], ["", "Квітка у волоссі Панни в’яне з кожною хвилиною її розпачу."]]);
    },

    update(dt, api) {
      if (S.done) return;
      const p = S.p;
      api.moveActor(p, dt, { x0: 20, x1: 940, y0: 70, y1: 520 });
      S.msgT -= dt; S.petalT -= dt;
      if (S.petalT <= 0) {
        S.petals--; S.petalT = PETAL_T; api.sfx("bad");
        if (S.petals <= 0) return wilted(api);
        api.banner(api.pick(["Панна: «Це точно сестра! Вона завжди заздрила!»", "Панна: «Подруги — віроломні!»", "Панна зачиняється в покоях і плаче", "Панна: «Нікому більше не вірю!»"]) + " (пелюсток: " + S.petals + ")", 3000);
      }
      if (api.input.act) act(api);
      api.hud([["Пелюсток", S.petals], ["Доказів", S.found.size + " з 3"], S.truth ? ["Правда", "відома"] : null]);
    },

    draw(ctx, api) {
      ctx.fillStyle = "#3d3340"; ctx.fillRect(0, 0, 960, 540);
      for (const r of ROOMS) { api.D.rr(r.x + 6, r.y + 6, r.w - 12, r.h - 12, 14, r.c); api.D.text(r.n, r.x + r.w / 2, r.y + 24, { size: 14, color: "#4a3a45", display: true }); }
      api.D.emoji("🌹", 700, 110, 34); api.D.emoji("🌳", 920, 120, 50); api.D.emoji("🍲", 60, 380, 34); api.D.emoji("💎", 900, 380, 30); api.D.emoji("🛏️", 260, 120, 50); api.D.emoji("🪞", 560, 120, 40);
      for (const c of CLUES) { const got = S.found.has(c.k); api.D.emoji(c.e, c.x, c.y + Math.sin(api.t * 3 + c.x) * (got ? 0 : 2), 30, { alpha: got ? 0.4 : 1 }); if (!got) api.D.text("?", c.x + 16, c.y - 16, { size: 14, color: "#c23b5b", display: true }); }
      for (const k in PEOPLE) {
        const q = PEOPLE[k];
        api.D.shadow(q.x, q.y + 20, 15); api.D.emoji(q.e, q.x, q.y, 42);
        api.D.text(q.n, q.x, q.y + 34, { size: 12, color: "#2e2430" });
      }
      // квітка Панни
      const pn = PEOPLE.panna;
      for (let i = 0; i < 6; i++) { const a = i / 6 * Math.PI * 2; if (i < S.petals) api.D.circle(pn.x + 28 + Math.cos(a) * 7, pn.y - 30 + Math.sin(a) * 7, 5, "#ff7aa8"); }
      api.D.circle(pn.x + 28, pn.y - 30, 4, "#ffd54a");
      api.drawActor(S.p);
      if (S.msgT > 0) api.D.bubble(S.msg, S.p.x, S.p.y - 26, { size: 13 });
    },
  };

  function msg(t) { S.msg = t; S.msgT = 3; }

  async function act(api) {
    const p = S.p;
    for (const c of CLUES) if (Math.hypot(p.x - c.x, p.y - c.y) < 50) { if (!S.found.has(c.k)) { S.found.add(c.k); api.sfx("pick"); } await api.say([["Нотатки детектива", c.t]]); return; }
    for (const k in PEOPLE) if (Math.hypot(p.x - PEOPLE[k].x, p.y - PEOPLE[k].y) < 58) return talk(api, k);
  }

  async function talk(api, k) {
    const who = PEOPLE[k].n;
    if (k === "panna") return panna(api);
    if (k === "sister") {
      const c = await api.choose("Ти мене підозрюєш? Питай.", ["Звідки розірвана нитка в саду?", "Ти заздриш сестрі?", "Що ти знаєш про намисто?"], who);
      await api.say([[who, ["Це моє власне намистечко порвалося, коли я поливала троянди. Скляне, копійчане.", "Заздрю? Я її люблю. Хоч вона зараз і не вірить нікому.", "Знаю, що Ювелір нанизував його на замовлення. Щось там було з днем народження."][c]]]);
    } else if (k === "friend") {
      const c = await api.choose("Ой, детективе… Ви про перлини на кухні?", ["Звідки у тебе дві перлини?", "Ти була в покоях Панни?", "Хто міг украсти?"], who);
      await api.say([[who, ["Це мої сережки! Застібка зламалася, ось я їх і поклала.", "Тиждень не була. Вона мене й на поріг не пускає.", "Ніхто. Але ж їй не поясниш…"][c]]]);
    } else if (k === "maid") {
      const c = await api.choose("Я прибираю тут двадцять років. Що вас цікавить?", ["Хто заходив до покоїв?", "Ти рахувала перлини?", "Звідки чек ювеліра?"], who);
      await api.say([[who, ["Тільки я і сама Панна. Скриня завжди замкнена.", "Ніколи. Я до них і не торкаюся.", "Ювелір приніс його разом з намистом. Я ще тоді пляму чорнилом поставила, вибачте."][c]]]);
    } else if (k === "jeweler") {
      const c = await api.choose("Добрий день. Чим можу допомогти?", ["Хто міг украсти перлини Панни?", "Яке гарне у вас каміння!", "Скільки перлин ви нанизали на намисто Панни?"], who);
      if (c === 2) { S.truth = true; api.sfx("good"); await api.say([[who, "Дев’яносто вісім. Так замовив її батько: по перлині на кожен місяць, відколи вона народилася. Хіба вона не знає?"]]); }
      else await api.say([[who, ["Я ювелір, а не сторож. Питайте про те, що я знаю.", "Дякую! Але ви ж не по каміння прийшли."][c]]]);
    }
  }

  async function panna(api) {
    const c = await api.choose("Ну що, детективе? Хто винен?", ["Ще розслідую", "Сестра Оля", "Подруга Марта", "Служниця", "Злочину не було"], "Панна");
    if (c === 0) return;
    S.done = true; api.locked = true;
    if (c >= 1 && c <= 3) {
      await api.say([["Панна", "Я так і знала! Зрадниця!"], ["", "Двері грюкають. Стрічка дружби, яку плели роками, розірвана."]]);
      api.locked = false; return api.end("А");
    }
    if (S.truth) {
      await api.say([["Детектив", "Ювелір нанизав рівно 98 перлин. Ваш батько так замовив: по одній на кожен місяць вашого життя."], ["Панна", "…Отже, нічого не пропало. А я тиждень підозрювала всіх."]]);
      api.locked = false; return api.end("Б");
    }
    await api.say([["Детектив", "Нитка — сестрина, перлини — подружині, у скриню ніхто не заходив. Може, нічого і не пропадало?"], ["Панна", "Може… Ну й нехай. Дев’яносто вісім — теж гарне число."]]);
    api.locked = false; api.end("Г");
  }

  async function wilted(api) {
    S.done = true; api.locked = true;
    await api.say([["", "Остання пелюстка падає. Панна зачиняє двері покоїв і більше нікого не пускає."]]);
    api.locked = false; api.end("В");
  }

  PG.start(game);
})();
